#!/usr/bin/env python3
"""char_variants.py — cast members that are variants of an existing rig.

`tools/artgen` draws the cast with Pillow, which this sandbox does not have. But
Bethlehem's household needs three more people than the rig had: Jesse, Eliab and
Samuel. Drawing new rigs blind would be worse than useless — the point of the
art direction is that everyone shares one body and one palette — so each new
person is a *variant* of the rig they belong to: the same silhouette, shifted in
colour the way the pack's own villagers are shifted.

    python3 tools/char_variants.py           # write the variant sheets
    python3 tools/char_variants.py --check   # verify they exist and differ

PNG is read and written with the standard library only (zlib), so this runs
anywhere, and the output is byte-identical on every machine. If the rigs are
ever regenerated by artgen, re-run this afterwards.

What each variant is and why:

  jesse   ← elder   an old man, but a farmer: the elder's blue-grey wool turns
                    the brown of a coat worn outdoors.
  eliab   ← boy     the eldest brother, the family's ruddy brown rather than a
                    boy's olive.
  samuel  ← priest  a prophet in indigo, not the priest's ivory — the two are
                    always within a few steps of each other in Bethlehem.
"""

import pathlib
import struct
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CHARS = ROOT / "art" / "characters"

# source rig -> new actor, with a per-channel multiplier and an optional
# lightness nudge applied to every opaque pixel
VARIANTS = {
    # actor      rig       robe hue: from -> to    sat floor   value
    "jesse":  {"from": "elder",  "hue": (210, 32),  "sat": 0.34, "val": 1.00},
    "eliab":  {"from": "boy",    "hue": (88, 14),   "sat": 0.42, "val": 0.96},
    "samuel": {"from": "priest", "hue": (43, 244),  "sat": 0.32, "val": 0.86},
}

# A robe is a hue plus shades of it. These bounds pick the cloth and leave the
# face alone: skin sits around 31° at 0.43 saturation, and the outline is
# near-black, so neither is in range.
CLOTH_SAT_MAX = 0.40
CLOTH_VAL_MIN = 0.40
HUE_TOL = 14

KINDS = ("idle", "walk")


# ── PNG, standard library only ────────────────────────────────────────────

def read_png(path):
    raw = path.read_bytes()
    if raw[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("%s: not a PNG" % path.name)
    pos = 8
    w = h = bit = colour = inter = 0
    idat = bytearray()
    while pos < len(raw):
        length = struct.unpack(">I", raw[pos:pos + 4])[0]
        kind = raw[pos + 4:pos + 8]
        body = raw[pos + 8:pos + 8 + length]
        if kind == b"IHDR":
            w, h, bit, colour, _comp, _filt, inter = struct.unpack(">IIBBBBB", body[:13])
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    if bit != 8 or colour != 6 or inter != 0:
        raise SystemExit("%s: expected 8-bit RGBA, non-interlaced" % path.name)
    data = zlib.decompress(bytes(idat))
    stride = w * 4
    out = bytearray(h * stride)
    prev = bytearray(stride)
    i = 0
    for y in range(h):
        filt = data[i]
        i += 1
        line = bytearray(data[i:i + stride])
        i += stride
        if filt == 1:
            for x in range(4, stride):
                line[x] = (line[x] + line[x - 4]) & 0xFF
        elif filt == 2:
            for x in range(stride):
                line[x] = (line[x] + prev[x]) & 0xFF
        elif filt == 3:
            for x in range(stride):
                left = line[x - 4] if x >= 4 else 0
                line[x] = (line[x] + ((left + prev[x]) >> 1)) & 0xFF
        elif filt == 4:
            for x in range(stride):
                a = line[x - 4] if x >= 4 else 0
                b = prev[x]
                c = prev[x - 4] if x >= 4 else 0
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                line[x] = (line[x] + pr) & 0xFF
        elif filt != 0:
            raise SystemExit("%s: unknown filter %d" % (path.name, filt))
        out[y * stride:(y + 1) * stride] = line
        prev = line
    return w, h, out


def write_png(path, w, h, rgba):
    stride = w * 4
    raw = bytearray()
    for y in range(h):
        raw.append(0)                       # filter: none
        raw += rgba[y * stride:(y + 1) * stride]

    def chunk(kind, body):
        return (struct.pack(">I", len(body)) + kind + body
                + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF))

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")
    path.write_bytes(png)


def _rgb_to_hsv(r, g, b):
    import colorsys
    return colorsys.rgb_to_hsv(r / 255.0, g / 255.0, b / 255.0)


def _hsv_to_rgb(h, s, v):
    import colorsys
    r, g, b = colorsys.hsv_to_rgb(h, s, v)
    return int(round(r * 255)), int(round(g * 255)), int(round(b * 255))


def shift(w, h, rgba, spec):
    """Recolour the cloth of a rig, keeping its face and its shading."""
    hue_from, hue_to = spec["hue"]
    out = bytearray(rgba)
    for i in range(0, len(out), 4):
        if out[i + 3] == 0:
            continue                         # never tint the transparent field
        hh, ss, vv = _rgb_to_hsv(out[i], out[i + 1], out[i + 2])
        deg = hh * 360.0
        if ss > CLOTH_SAT_MAX or vv < CLOTH_VAL_MIN:
            continue                         # skin, outline, deepest shadow
        delta = abs(((deg - hue_from + 180) % 360) - 180)
        if delta > HUE_TOL:
            continue
        r, g, b = _hsv_to_rgb(hue_to / 360.0, max(ss, spec["sat"]),
                              min(1.0, vv * spec["val"]))
        out[i], out[i + 1], out[i + 2] = r, g, b
    return out


def build():
    made = []
    for actor, spec in VARIANTS.items():
        src = spec["from"]
        for kind in KINDS:
            s = CHARS / ("%s_%s.png" % (src, kind))
            if not s.exists():
                raise SystemExit("missing rig %s" % s.name)
            w, h, rgba = read_png(s)
            out = shift(w, h, rgba, spec)
            dst = CHARS / ("%s_%s.png" % (actor, kind))
            write_png(dst, w, h, out)
            made.append(dst.name)
    return made


def check():
    problems = []
    for actor, spec in VARIANTS.items():
        for kind in KINDS:
            dst = CHARS / ("%s_%s.png" % (actor, kind))
            src = CHARS / ("%s_%s.png" % (spec["from"], kind))
            if not dst.exists():
                problems.append("%s is missing — run tools/char_variants.py" % dst.name)
                continue
            if not src.exists():
                problems.append("%s has no rig to vary (%s)" % (dst.name, src.name))
                continue
            w1, h1, a = read_png(dst)
            w2, h2, b = read_png(src)
            if (w1, h1) != (w2, h2):
                problems.append("%s is %dx%d but its rig is %dx%d" % (dst.name, w1, h1, w2, h2))
            elif a == b:
                problems.append("%s is byte-identical to its rig — no variant applied" % dst.name)
    if problems:
        for p in problems:
            print("  " + p)
        raise SystemExit("check_chars: %d problem(s)" % len(problems))
    print("check_chars: clean — %d variant actor(s) from %d rig(s)"
          % (len(VARIANTS), len({v["from"] for v in VARIANTS.values()})))


if __name__ == "__main__":
    if "--check" in sys.argv:
        check()
    else:
        for name in build():
            print("wrote art/characters/" + name)
        check()
